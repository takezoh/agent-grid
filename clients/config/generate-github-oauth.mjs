import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "../..");
const configPath = resolve(import.meta.dirname, "github.production.json");
const fixturePath = resolve(import.meta.dirname, "fixtures/github-oauth-valid.json");
const workspacePath = resolve(root, "clients/workspace/src/main/github-oauth.generated.ts");
const webHostPath = resolve(root, "clients/web-host/internal/githubhost/github_oauth_generated.go");
const placeholder = "Ov23liAgentGridDeviceFlow";

const config = JSON.parse(readFileSync(configPath, "utf8"));
if (
  config.schema_version !== 1 ||
  typeof config.app_id !== "string" ||
  !/^[0-9]+$/.test(config.app_id) ||
  typeof config.client_id !== "string" ||
  config.client_id.length === 0 ||
  config.client_id === placeholder ||
  JSON.stringify(config.scopes) !== JSON.stringify(["read:user", "repo"])
) {
  throw new Error("github production OAuth config is missing, placeholder, or has unsupported scopes");
}

const fixture = JSON.parse(readFileSync(fixturePath, "utf8"));
if (JSON.stringify(fixture) !== JSON.stringify(config)) {
  throw new Error("github OAuth fixture must equal the production config");
}

const ts = `// Generated by clients/config/generate-github-oauth.mjs; DO NOT EDIT.\n` +
  `export const FIXED_APP_ID = ${JSON.stringify(config.app_id)};\n` +
  `export const FIXED_CLIENT_ID = ${JSON.stringify(config.client_id)};\n` +
  `export const SCOPE_READ_USER = ${JSON.stringify(config.scopes[0])};\n` +
  `export const SCOPE_REPO = ${JSON.stringify(config.scopes[1])};\n`;
const go = `// Code generated by clients/config/generate-github-oauth.mjs; DO NOT EDIT.\n` +
  `package githubhost\n\n` +
  `const (\n` +
  `\tFixedAppID    = ${JSON.stringify(config.app_id)}\n` +
  `\tFixedClientID = ${JSON.stringify(config.client_id)}\n` +
  `\tScopeReadUser = ${JSON.stringify(config.scopes[0])}\n` +
  `\tScopeRepo     = ${JSON.stringify(config.scopes[1])}\n` +
  `)\n`;

const outputs = [[workspacePath, ts], [webHostPath, go]];
if (process.argv.includes("--check")) {
  for (const [file, expected] of outputs) {
    if (readFileSync(file, "utf8") !== expected) {
      throw new Error(`${file} is stale; run node clients/config/generate-github-oauth.mjs`);
    }
  }
} else {
  for (const [file, content] of outputs) writeFileSync(file, content);
}
